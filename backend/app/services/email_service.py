import os
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from datetime import datetime

EMAIL_FROM = os.getenv("EMAIL_FROM", "noreply@veogen.com")
EMAIL_SMTP = os.getenv("EMAIL_SMTP", "dev")  # Default to dev mode
EMAIL_PORT = int(os.getenv("EMAIL_PORT", "587"))  # Use 587 for TLS
EMAIL_USER = os.getenv("EMAIL_USER", "")
EMAIL_PASS = os.getenv("EMAIL_PASS", "")
EMAIL_DEV_OUTBOX = os.getenv("EMAIL_DEV_OUTBOX", "dev_emails/")

# Ensure dev_emails directory exists
os.makedirs(EMAIL_DEV_OUTBOX, exist_ok=True)

def send_email(to: str, subject: str, body: str, html: str = None):
    """Send an email via SMTP or write to file if in dev mode."""
    print(f"[EMAIL DEBUG] EMAIL_SMTP={EMAIL_SMTP}, to={to}, subject={subject}")
    
    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = EMAIL_FROM
    msg["To"] = to
    part1 = MIMEText(body, "plain")
    msg.attach(part1)
    if html:
        part2 = MIMEText(html, "html")
        msg.attach(part2)
    
    # Always save to file first (for debugging and backup)
    try:
        timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
        safe_email = to.replace('@', '_at_').replace('.', '_')
        filename = f"{EMAIL_DEV_OUTBOX}/email_{timestamp}_{safe_email}.eml"
        
        with open(filename, "w", encoding="utf-8") as f:
            f.write(msg.as_string())
        print(f"[DEV EMAIL] Saved to {filename}")
        
        # Also create an HTML preview file
        html_filename = f"{EMAIL_DEV_OUTBOX}/email_{timestamp}_{safe_email}.html"
        with open(html_filename, "w", encoding="utf-8") as f:
            f.write(f"""
<!DOCTYPE html>
<html>
<head>
    <title>Email: {subject}</title>
    <style>
        body {{ font-family: Arial, sans-serif; max-width: 600px; margin: 20px auto; padding: 20px; }}
        .header {{ background: #f0f0f0; padding: 10px; border-radius: 5px; margin-bottom: 20px; }}
        .content {{ background: white; padding: 20px; border: 1px solid #ddd; }}
        .footer {{ margin-top: 20px; font-size: 12px; color: #666; }}
    </style>
</head>
<body>
    <div class="header">
        <strong>To:</strong> {to}<br>
        <strong>From:</strong> {EMAIL_FROM}<br>
        <strong>Subject:</strong> {subject}<br>
        <strong>Time:</strong> {datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S")} UTC
    </div>
    <div class="content">
        {html if html else f'<pre>{body}</pre>'}
    </div>
    <div class="footer">
        <em>This email was generated by VeoGen development system</em>
    </div>
</body>
</html>
            """)
        print(f"[DEV EMAIL] HTML preview: {html_filename}")
        
    except Exception as e:
        print(f"[EMAIL FILE ERROR] {e}")
    
    # Try SMTP if configured (not in dev mode)
    try:
        if EMAIL_SMTP != "dev" and EMAIL_SMTP != "localhost" and EMAIL_USER and EMAIL_PASS:
            print(f"[EMAIL] Attempting SMTP send via {EMAIL_SMTP}:{EMAIL_PORT}")
            with smtplib.SMTP(EMAIL_SMTP, EMAIL_PORT) as server:
                server.starttls()
                server.login(EMAIL_USER, EMAIL_PASS)
                server.sendmail(EMAIL_FROM, to, msg.as_string())
            print(f"[EMAIL] Successfully sent to {to}")
            return True
        else:
            print(f"[EMAIL] Using dev mode - email saved to file only")
            return True
            
    except Exception as e:
        print(f"[EMAIL SMTP ERROR] {e}")
        print(f"[EMAIL] Falling back to dev mode - email saved to file")
        return True  # Still return True since we saved to file 