def install_python_dependencies():
    """Install required Python dependencies"""
    try:
        logger.info("📦 Installing Python dependencies...")
        
        # Check if we're in a virtual environment
        in_venv = hasattr(sys, 'real_prefix') or (hasattr(sys, 'base_prefix') and sys.base_prefix != sys.prefix)
        
        if not in_venv:
            logger.warning("⚠️  Not in a virtual environment. Consider using 'python -m venv venv' and activating it.")
        
        # Install dependencies
        result = subprocess.run([
            sys.executable, '-m', 'pip', 'install', '-r', 'requirements.txt'
        ], capture_output=True, text=True)
        
        if result.returncode == 0:
            logger.info("✅ Python dependencies installed successfully")
            return True
        else:
            logger.error(f"❌ Failed to install dependencies: {result.stderr}")
            return False
            
    except Exception as e:
        logger.error(f"❌ Error installing dependencies: {e}")
        return False

def initialize_database_schema():
    """Initialize database schema using our init script"""
    try:
        logger.info("🗃️  Initializing database schema...")
        
        # Run our database initialization script
        result = subprocess.run([
            sys.executable, 'init_database.py'
        ], capture_output=True, text=True)
        
        if result.returncode == 0:
            logger.info("✅ Database schema initialized successfully")
            logger.info(result.stdout)
            return True
        else:
            logger.error(f"❌ Failed to initialize schema: {result.stderr}")
            return False
            
    except Exception as e:
        logger.error(f"❌ Error initializing schema: {e}")
        return False

