#!/usr/bin/env python3
"""
PostgreSQL Database Setup and Configuration Script for VeoGen
Configures PostgreSQL, creates database, and initializes with proper settings
"""

import os
import sys
import subprocess
import logging
from pathlib import Path

# Setup logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def check_postgresql_installed():
    """Check if PostgreSQL is installed and running"""
    try:
        # Check if psql is available
        result = subprocess.run(['psql', '--version'], capture_output=True, text=True)
        if result.returncode == 0:
            logger.info(f"✅ PostgreSQL is installed: {result.stdout.strip()}")
            return True
        else:
            logger.error("❌ PostgreSQL is not installed or not in PATH")
            return False
    except FileNotFoundError:
        logger.error("❌ PostgreSQL is not installed or not in PATH")
        return False

def check_postgresql_running():
    """Check if PostgreSQL service is running"""
    try:
        # Try to connect to PostgreSQL
        result = subprocess.run([
            'psql', '-h', 'localhost', '-U', 'postgres', '-c', 'SELECT version();'
        ], capture_output=True, text=True, input='postgres\n')
        
        if result.returncode == 0:
            logger.info("✅ PostgreSQL service is running")
            return True
        else:
            logger.warning("⚠️ PostgreSQL service may not be running")
            return False
    except Exception as e:
        logger.warning(f"⚠️ Could not verify PostgreSQL service status: {e}")
        return False

def create_database_and_user():
    """Create VeoGen database and user"""
    try:
        logger.info("🔧 Creating VeoGen database and user...")
        
        # SQL commands to create database and user
        sql_commands = [
            "CREATE USER veogen WITH PASSWORD 'veogen123';",
            "CREATE DATABASE veogen OWNER veogen;",
            "GRANT ALL PRIVILEGES ON DATABASE veogen TO veogen;",
            "ALTER USER veogen CREATEDB;"
        ]
        
        for sql in sql_commands:
            try:
                result = subprocess.run([
                    'psql', '-h', 'localhost', '-U', 'postgres', '-c', sql
                ], capture_output=True, text=True)
                
                if result.returncode == 0:
                    logger.info(f"✅ Executed: {sql}")
                else:
                    if "already exists" in result.stderr:
                        logger.info(f"ℹ️  Already exists: {sql}")
                    else:
                        logger.warning(f"⚠️ Warning executing {sql}: {result.stderr}")
                        
            except Exception as e:
                logger.error(f"❌ Error executing {sql}: {e}")
        
        logger.info("✅ Database setup completed")
        return True
        
    except Exception as e:
        logger.error(f"❌ Failed to create database and user: {e}")
        return False

def test_connection():
    """Test connection to VeoGen database"""
    try:
        logger.info("🔍 Testing connection to VeoGen database...")
        
        # Test connection as veogen user
        result = subprocess.run([
            'psql', '-h', 'localhost', '-U', 'veogen', '-d', 'veogen', '-c', 'SELECT current_database(), current_user;'
        ], capture_output=True, text=True, env={**os.environ, 'PGPASSWORD': 'veogen123'})
        
        if result.returncode == 0:
            logger.info("✅ Successfully connected to VeoGen database")
            logger.info(f"Connection details: {result.stdout.strip()}")
            return True
        else:
            logger.error(f"❌ Failed to connect to VeoGen database: {result.stderr}")
            return False
            
    except Exception as e:
        logger.error(f"❌ Connection test failed: {e}")
        return False

