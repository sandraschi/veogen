def main():
    """Main setup function"""
    logger.info("🚀 Starting VeoGen PostgreSQL Setup...")
    
    # Step 1: Check PostgreSQL installation
    logger.info("\n1️⃣ Checking PostgreSQL installation...")
    if not check_postgresql_installed():
        logger.error("❌ Setup failed: PostgreSQL not installed")
        logger.info("💡 Please install PostgreSQL first:")
        logger.info("   - Windows: Download from https://www.postgresql.org/download/windows/")
        logger.info("   - macOS: brew install postgresql")
        logger.info("   - Linux: sudo apt-get install postgresql postgresql-contrib")
        sys.exit(1)
    
    # Step 2: Check PostgreSQL service
    logger.info("\n2️⃣ Checking PostgreSQL service...")
    if not check_postgresql_running():
        logger.warning("⚠️  PostgreSQL service may not be running")
        logger.info("💡 Try starting PostgreSQL:")
        logger.info("   - Windows: net start postgresql-x64-13")
        logger.info("   - macOS: brew services start postgresql")
        logger.info("   - Linux: sudo systemctl start postgresql")
    
    # Step 3: Create database and user
    logger.info("\n3️⃣ Creating database and user...")
    if not create_database_and_user():
        logger.error("❌ Failed to create database and user")
        logger.info("💡 You may need to:")
        logger.info("   - Ensure PostgreSQL is running")
        logger.info("   - Check that you can connect as postgres user")
        logger.info("   - Verify PostgreSQL authentication settings")
        sys.exit(1)
    
    # Step 4: Test connection
    logger.info("\n4️⃣ Testing database connection...")
    if not test_connection():
        logger.error("❌ Database connection test failed")
        sys.exit(1)
    
    # Step 5: Create .env file
    logger.info("\n5️⃣ Creating environment configuration...")
    if not create_env_file():
        logger.error("❌ Failed to create .env file")
        sys.exit(1)
    
    # Step 6: Install dependencies
    logger.info("\n6️⃣ Installing Python dependencies...")
    if not install_python_dependencies():
        logger.error("❌ Failed to install dependencies")
        sys.exit(1)
    
    # Step 7: Initialize schema
    logger.info("\n7️⃣ Initializing database schema...")
    if not initialize_database_schema():
        logger.error("❌ Failed to initialize database schema")
        sys.exit(1)
    
    # Success summary
    print_setup_summary()

if __name__ == "__main__":
    main()
